#!/usr/bin/env node
/**
 * Bundle runtime/src/*.js into a single ES module at runtime/dream.js.
 *
 * Usage:
 *   node scripts/bundle-runtime.mjs           # write runtime/dream.js
 *   node scripts/bundle-runtime.mjs --check   # exit 1 if dream.js is stale
 *
 * Also used by the compiler to assemble a selective *.runtime.js:
 *   import { bundleRuntime } from './bundle-runtime.mjs';
 *   bundleRuntime({ entry: '...', hosts: ['js','fs'], outPath: '...' })
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(__dirname, "..");
const SRC_ROOT = path.join(REPO_ROOT, "runtime", "src");
const DEFAULT_OUT = path.join(REPO_ROOT, "runtime", "dream.js");

const IMPORT_RE = /^\s*import\s+(?:([\s\S]*?)\s+from\s+)?["']([^"']+)["']\s*;?\s*$/gm;
const SIDE_IMPORT_RE = /^\s*import\s+["']([^"']+)["']\s*;?\s*$/gm;

/** Resolve a relative import from `fromFile` under SRC_ROOT. */
function resolveImport(fromFile, spec) {
  if (!spec.startsWith(".")) return null; // node: / bare — leave for runtime
  const base = path.resolve(path.dirname(fromFile), spec);
  const candidates = [base, base + ".js", path.join(base, "index.js")];
  for (const c of candidates) {
    if (fs.existsSync(c) && fs.statSync(c).isFile()) return c;
  }
  throw new Error(`cannot resolve '${spec}' from ${fromFile}`);
}

/** Collect transitive ESM deps of `entry` (absolute paths), in topo order (deps first). */
function collectModules(entryAbs) {
  const ordered = [];
  const visiting = new Set();
  const done = new Set();

  function visit(file) {
    if (done.has(file)) return;
    if (visiting.has(file)) throw new Error(`circular import: ${file}`);
    visiting.add(file);
    const text = fs.readFileSync(file, "utf8");
    const deps = [];
    for (const m of text.matchAll(/^\s*import\s+[\s\S]*?from\s+["']([^"']+)["']/gm)) {
      const resolved = resolveImport(file, m[1]);
      if (resolved) deps.push(resolved);
    }
    for (const m of text.matchAll(/^\s*import\s+["']([^"']+)["']/gm)) {
      const resolved = resolveImport(file, m[1]);
      if (resolved) deps.push(resolved);
    }
    for (const d of deps) visit(d);
    visiting.delete(file);
    done.add(file);
    ordered.push(file);
  }

  visit(entryAbs);
  return ordered;
}

/**
 * Strip import lines and rewrite `export` so names stay in module scope.
 * Dynamic `import("node:...")` is preserved.
 */
function transformModule(text, filePath) {
  const rel = path.relative(SRC_ROOT, filePath);
  let body = text;

  // Remove static import lines (including multi-line).
  body = body.replace(/^\s*import\s+[\s\S]*?from\s+["'][^"']+["']\s*;?\s*$/gm, "");
  body = body.replace(/^\s*import\s+["'][^"']+["']\s*;?\s*$/gm, "");

  // export async function / export function / export class / export const / export let
  body = body.replace(/^export\s+(async\s+function\s+)/gm, "$1");
  body = body.replace(/^export\s+(function\s+)/gm, "$1");
  body = body.replace(/^export\s+(class\s+)/gm, "$1");
  body = body.replace(/^export\s+(const\s+)/gm, "$1");
  body = body.replace(/^export\s+(let\s+)/gm, "$1");

  // export { a, b as c } / export default
  body = body.replace(/^export\s+default\s+/gm, "const __default_export__ = ");
  body = body.replace(/^export\s*\{[^}]*\}\s*;?\s*$/gm, "");

  return `\n// ----- ${rel} -----\n${body.trim()}\n`;
}

/**
 * Bundle starting from an entry module under runtime/src.
 * @param {{ entry?: string, outPath?: string, header?: string }} opts
 * @returns {string} bundled source
 */
export function bundleRuntime(opts = {}) {
  const entryRel = opts.entry || "load.js";
  const entryAbs = path.isAbsolute(entryRel)
    ? entryRel
    : path.join(SRC_ROOT, entryRel);
  const modules = collectModules(entryAbs);

  const header =
    opts.header ||
    `// Dream JS interop runtime.
//
// GENERATED by scripts/bundle-runtime.mjs — do not edit by hand.
// Sources live under runtime/src/. Regenerate with:
//   node scripts/bundle-runtime.mjs
//
// Loads a Dream-compiled .wasm module, wires the default env builtins, and lets you bind
// JavaScript implementations to extern fun declarations with automatic value marshaling.
// Works as an ES module in both the browser and Node.
`;

  let out = header + "\n";
  for (const file of modules) {
    out += transformModule(fs.readFileSync(file, "utf8"), file);
  }

  out += `
export { load, run, DreamInstance, TAGS, HEAP_HEADER_SIZE };
export default { load, run, DreamInstance, TAGS, HEAP_HEADER_SIZE };
`;

  if (opts.outPath) {
    fs.mkdirSync(path.dirname(opts.outPath), { recursive: true });
    fs.writeFileSync(opts.outPath, out);
  }
  return out;
}

/** Chunk ids → relative source entry factories for selective assembly. */
export const HOST_CHUNKS = {
  js: "hosts/js.js",
  http: "hosts/http.js",
  fs: "hosts/fs.js",
  crypto: "hosts/crypto.js",
  gpu: "hosts/gpu.js",
  console_process: "hosts/console_process.js",
  datetime_text: "hosts/datetime_text.js",
  workers: "workers.js",
  env: "hosts/env.js",
};

/**
 * Map a WASM/ABI import field name to the host chunk id that implements it.
 * Returns null for env builtins (print_*, Math) handled by defaultEnv.
 */
export function chunkForImportField(field) {
  if (!field) return null;
  if (field.startsWith("js")) return "js";
  if (field.startsWith("http")) return "http";
  if (field.startsWith("file") || field.startsWith("dir")) return "fs";
  if (field.startsWith("crypto")) return "crypto";
  if (field.startsWith("gpu") || field === "__attachGpuAbi") return "gpu";
  if (field.startsWith("worker")) return "workers";
  if (
    field.startsWith("console") ||
    field.startsWith("process")
  ) {
    return "console_process";
  }
  if (
    field.startsWith("unicode") ||
    field.startsWith("date") ||
    field.startsWith("time") ||
    field === "delayMs"
  ) {
    return "datetime_text";
  }
  return null;
}

function main() {
  const check = process.argv.includes("--check");
  const bundled = bundleRuntime({ entry: "load.js" });
  if (check) {
    if (!fs.existsSync(DEFAULT_OUT)) {
      console.error("runtime/dream.js missing; run: node scripts/bundle-runtime.mjs");
      process.exit(1);
    }
    const existing = fs.readFileSync(DEFAULT_OUT, "utf8");
    if (existing !== bundled) {
      console.error("runtime/dream.js is stale; run: node scripts/bundle-runtime.mjs");
      process.exit(1);
    }
    console.log("runtime/dream.js is up to date");
    return;
  }
  fs.writeFileSync(DEFAULT_OUT, bundled);
  console.log(`wrote ${path.relative(REPO_ROOT, DEFAULT_OUT)} (${bundled.length} bytes)`);
}

const isMain =
  process.argv[1] &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);

if (isMain) main();
